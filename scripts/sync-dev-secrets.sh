#!/usr/bin/env bash
#
# sync-dev-secrets.sh - Generate local dev secrets from .env
#
# This script derives secrets (htpasswd, JDBC credentials, DB passwords)
# from the master VLC_DEV_PASSWORD in .env. Run this after cloning or
# whenever .env changes.
#
# Usage:
#   ./scripts/sync-dev-secrets.sh
#
set -euo pipefail
cd "$(dirname "$0")/.."

log() { echo "[secrets] $*"; }
err() { echo "[secrets] ERROR: $*" >&2; exit 1; }

# --- Validating .env exists ---
if [ ! -f .env ]; then
  err ".env file not found. Copy .env.example to .env and set VLC_DEV_PASSWORD."
fi

# --- Loading .env ---
log "Loading .env ..."
set -a
# shellcheck disable=SC1091
. .env
set +a

# --- Validating required variables ---
if [ -z "${VLC_DEV_PASSWORD:-}" ]; then
  err "VLC_DEV_PASSWORD not set in .env"
fi

log "Generating secrets from VLC_DEV_PASSWORD ..."

# --- 1) Nginx Basic Auth ---
log "Creating compose/.htpasswd (nginx basic auth) ..."
mkdir -p compose
printf "admin:%s\n" "$(openssl passwd -apr1 "$VLC_DEV_PASSWORD")" > compose/.htpasswd
chmod 644 compose/.htpasswd  # readable by nginx in container

# --- 2) Kafka Connect secrets ---
log "Creating connect/secrets/secrets.properties (JDBC credentials) ..."
mkdir -p connect/secrets
cat > connect/secrets/secrets.properties <<EOF
TS_JDBC_URL=jdbc:postgresql://timescaledb:5432/vlc
TS_USERNAME=vlc_dev
TS_PASSWORD=${VLC_DEV_PASSWORD}
EOF
chmod 600 connect/secrets/secrets.properties

# --- 3) DB password override script (for fresh DB init) ---
log "Creating db/init/020-vlc-password.override.sql (Postgres password) ..."
mkdir -p db/init
cat > db/init/020-vlc-password.override.sql <<EOF
-- Auto-generated by sync-dev-secrets.sh - DO NOT COMMIT
ALTER ROLE vlc_dev WITH PASSWORD '${VLC_DEV_PASSWORD}';
EOF
chmod 600 db/init/020-vlc-password.override.sql

# --- 4) Alertmanager config ---
# The shared Gmail sender: the address from email/.env and the app password from the WSL keyring.
# The generated file is the one plain copy, a documented exception, because Alertmanager reads its
# password only from a file. It stays 600, so the container runs as its owner.
log "Creating monitoring/alertmanager/alertmanager.generated.yml (SMTP credentials) ..."
EMAIL_ENV="${EMAIL_ENV:-/mnt/c/acidvuca/email/.env}"
[ -f "$EMAIL_ENV" ] || err "$EMAIL_ENV not found: it holds GMAIL_2_USER, the alert sender. Set EMAIL_ENV to its path."
SMTP_USER="$(sed -n 's/^GMAIL_2_USER=//p' "$EMAIL_ENV" | tr -d '\r')"
[ -n "$SMTP_USER" ] || err "GMAIL_2_USER not set in $EMAIL_ENV"
[ -n "${SMTP_TO:-}" ] || err "SMTP_TO not set in .env: alerts need a recipient."
command -v keyring >/dev/null || err "keyring not found on PATH: the Gmail app password lives there."
log "Reading the Gmail app password; the keyring asks for its master password ..."
SMTP_PASSWORD="$(keyring get email gmail_2_password || true)"
SMTP_PASSWORD="${SMTP_PASSWORD// /}"  # to drop the spaces Google displays
[ -n "$SMTP_PASSWORD" ] || err "No gmail_2_password under the email service in the keyring."
mkdir -p monitoring/alertmanager/data
# Restricting the file before it holds the password
: > monitoring/alertmanager/alertmanager.generated.yml
chmod 600 monitoring/alertmanager/alertmanager.generated.yml
SMTP_USER="$SMTP_USER" SMTP_TO="$SMTP_TO" SMTP_PASSWORD="$SMTP_PASSWORD" \
  envsubst '${SMTP_USER} ${SMTP_TO} ${SMTP_PASSWORD}' \
  < monitoring/alertmanager/alertmanager.yml \
  > monitoring/alertmanager/alertmanager.generated.yml
unset SMTP_PASSWORD

# --- 5) Producer .env (if needed for local testing) ---
if [ -d producer ]; then
  log "Ensuring producer can access Schema Registry ..."
  # Producer reads SCHEMA_REGISTRY_URL from env or defaults to http://schema-registry:8081
fi

log "Done. Generated files:"
log "  - compose/.htpasswd"
log "  - connect/secrets/secrets.properties"
log "  - db/init/020-vlc-password.override.sql"
log "  - monitoring/alertmanager/alertmanager.generated.yml"
log ""
log "Next steps:"
log "  1. Start infra: docker compose --profile infra up -d"
log "  2. Bootstrap Kafka: ./scripts/bootstrap_kafka.sh"
log "  3. Deploy connectors: ./scripts/post_connectors.sh deploy"

